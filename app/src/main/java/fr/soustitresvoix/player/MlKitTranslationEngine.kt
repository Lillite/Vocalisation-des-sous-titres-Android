package fr.soustitresvoix.player

import android.content.Context
import com.google.android.gms.tasks.Task
import com.google.mlkit.common.MlKit
import com.google.mlkit.common.model.DownloadConditions
import com.google.mlkit.nl.translate.TranslateLanguage
import com.google.mlkit.nl.translate.Translation
import com.google.mlkit.nl.translate.TranslatorOptions
import fr.soustitresvoix.core.TranslationPlan
import java.io.Closeable
import java.util.Locale
import java.util.concurrent.CountDownLatch
import java.util.concurrent.Executor
import java.util.concurrent.TimeUnit
import java.util.concurrent.atomic.AtomicBoolean

/**
 * Official on-device Google translator. The selected language pair owns one
 * reusable translator and one model preparation, not one download per subtitle.
 * All blocking work belongs to the translation worker. Closing never waits for
 * that worker, and late SDK completions cannot publish a partial result.
 */
class MlKitTranslationEngine internal constructor(
    override val id: String,
    private val allowMobileDownload: Boolean,
    private val backendFactory: (String, String) -> MlKitTranslationBackend,
    private val limits: WaitLimits = WaitLimits()
) : TranslationEngine {
    override val maxBatchCharacters: Int get() = TranslationPlan.MAX_CUE_CHARACTERS

    constructor(context: Context, id: String, allowMobileDownload: Boolean = false) :
        this(id, allowMobileDownload, officialFactory(context))

    internal data class WaitLimits(
        val modelMillis: Long = 300_000,
        val textMillis: Long = 30_000,
        val pollMillis: Long = 100
    ) {
        init { require(modelMillis > 0 && textMillis > 0 && pollMillis in 1..100) }
    }

    private val closed = AtomicBoolean(false)
    private val stateLock = Any()
    private val callLock = Any()
    private var backend: MlKitTranslationBackend? = null
    // Only the serialized translation worker accesses pair and prepared.
    private var pair: Pair<String, String>? = null
    private var prepared = false

    override fun translate(texts: List<String>, sourceLanguage: String, targetLanguage: String,
        cancelled: () -> Boolean): List<String> = synchronized(callLock) {
        checkCancelled(cancelled)
        val source = canonicalLanguage(sourceLanguage)
            ?: throw TranslationFailure(TranslationFailure.Reason.LANGUAGE)
        val target = canonicalLanguage(targetLanguage)
            ?: throw TranslationFailure(TranslationFailure.Reason.LANGUAGE)
        if (source == target) throw TranslationFailure(TranslationFailure.Reason.LANGUAGE)
        if (texts.isEmpty() || texts.size > MAX_ITEMS || texts.any { !validText(it) } ||
            texts.sumOf { it.length.toLong() } > MAX_INPUT_CHARACTERS)
            throw TranslationFailure(TranslationFailure.Reason.CONFIGURATION)

        val current = translator(source, target, cancelled)
        if (!prepared) {
            val model = safely(TranslationFailure.Reason.MODEL_DOWNLOAD) {
                current.prepareModels(allowMobileDownload)
            }
            await(model, limits.modelMillis, TranslationFailure.Reason.MODEL_DOWNLOAD, cancelled)
            prepared = true
        }
        val output = ArrayList<String>(texts.size)
        // Keep every occurrence, including identical signs or repeated dialogue.
        // No linguistic boundary or timestamp is sent to, or generated by, ML Kit.
        for (text in texts) {
            checkCancelled(cancelled)
            val task = safely(TranslationFailure.Reason.LOCAL_TRANSLATION) { current.translate(text) }
            val translated = await(task, limits.textMillis, TranslationFailure.Reason.LOCAL_TRANSLATION, cancelled)
            if (translated == null || !validText(translated))
                throw TranslationFailure(TranslationFailure.Reason.RESPONSE)
            output += translated
        }
        checkCancelled(cancelled)
        output
    }

    private fun translator(source: String, target: String, cancelled: () -> Boolean): MlKitTranslationBackend {
        val requested = source to target
        if (pair != requested) {
            val previous = synchronized(stateLock) { backend.also { backend = null } }
            runCatching { previous?.close() }
            prepared = false
            pair = null
        }
        synchronized(stateLock) { backend }?.let { return it }
        checkCancelled(cancelled)
        val created = safely(TranslationFailure.Reason.LOCAL_TRANSLATION) { backendFactory(source, target) }
        synchronized(stateLock) {
            if (closed.get() || cancelled() || Thread.currentThread().isInterrupted) {
                runCatching { created.close() }
                throw TranslationCancelledException()
            }
            backend = created
        }
        pair = requested
        return created
    }

    private fun <T> await(task: Task<T>, timeoutMillis: Long, reason: TranslationFailure.Reason,
        cancelled: () -> Boolean): T? {
        val completion = CountDownLatch(1)
        // Explicit executor: SDK callbacks must not wait for the activity/main
        // looper, which may be recreating while our retained worker is running.
        task.addOnCompleteListener(DIRECT_EXECUTOR) { completion.countDown() }
        val started = System.nanoTime()
        val timeoutNanos = TimeUnit.MILLISECONDS.toNanos(timeoutMillis)
        while (!task.isComplete) {
            checkCancelled(cancelled)
            val remaining = timeoutNanos - (System.nanoTime() - started)
            if (remaining <= 0) throw TranslationFailure(reason)
            try {
                completion.await(minOf(remaining, TimeUnit.MILLISECONDS.toNanos(limits.pollMillis)), TimeUnit.NANOSECONDS)
            } catch (_: InterruptedException) {
                Thread.currentThread().interrupt()
                throw TranslationCancelledException()
            }
        }
        checkCancelled(cancelled)
        if (task.isCanceled) throw TranslationCancelledException()
        if (!task.isSuccessful) throw TranslationFailure(reason)
        return safely(reason) { task.result }
    }

    private fun checkCancelled(cancelled: () -> Boolean) {
        if (closed.get() || cancelled() || Thread.currentThread().isInterrupted)
            throw TranslationCancelledException()
    }

    override fun close() {
        if (!closed.compareAndSet(false, true)) return
        val previous = synchronized(stateLock) { backend.also { backend = null } }
        runCatching { previous?.close() }
        // ML Kit does not expose cancellation of an already scheduled model
        // download. The wait stops promptly; the SDK may finish that download.
    }

    companion object {
        private const val MAX_ITEMS = 64
        private const val MAX_INPUT_CHARACTERS = 64L * 24_000
        private val DIRECT_EXECUTOR = Executor { it.run() }
        private val LANGUAGE_TAG = Regex("[A-Za-z]{2,3}(?:-[A-Za-z0-9]{2,8}){0,3}")

        /** Uses the official supported-language registry, including BCP-47 aliases. */
        fun canonicalLanguage(tag: String): String? {
            if (!LANGUAGE_TAG.matches(tag)) return null
            return TranslateLanguage.fromLanguageTag(tag.lowercase(Locale.ROOT))
        }

        fun supportedLanguages(): List<String> = TranslateLanguage.getAllLanguages().sorted()

        private fun validText(text: String): Boolean = text.isNotBlank() &&
            text.length <= TranslationPlan.MAX_CUE_CHARACTERS && '\u0000' !in text &&
            Charsets.UTF_8.newEncoder().canEncode(text)

        private fun <T> safely(reason: TranslationFailure.Reason, action: () -> T): T = try { action() }
            catch (failure: TranslationCancelledException) { throw failure }
            catch (_: Exception) { throw TranslationFailure(reason) }

        private fun officialFactory(context: Context): (String, String) -> MlKitTranslationBackend {
            val application = context.applicationContext
            return { source, target ->
                // Explicit initialization also supports disabling the automatic
                // SDK content provider, so startup need not initialize ML Kit.
                MlKit.initialize(application)
                OfficialMlKitTranslationBackend(source, target)
            }
        }
    }
}

/** Test seam represents only asynchronous SDK operations, never Android stubs. */
internal interface MlKitTranslationBackend : Closeable {
    fun prepareModels(allowMobileDownload: Boolean): Task<Void>
    fun translate(text: String): Task<String>
}

private class OfficialMlKitTranslationBackend(source: String, target: String) : MlKitTranslationBackend {
    private val translator = Translation.getClient(TranslatorOptions.Builder()
        .setSourceLanguage(source).setTargetLanguage(target).build())

    override fun prepareModels(allowMobileDownload: Boolean): Task<Void> {
        val conditions = DownloadConditions.Builder()
        if (!allowMobileDownload) conditions.requireWifi()
        return translator.downloadModelIfNeeded(conditions.build())
    }

    override fun translate(text: String): Task<String> = translator.translate(text)
    override fun close() = translator.close()
}
