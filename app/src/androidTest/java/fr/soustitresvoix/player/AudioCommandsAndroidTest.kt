/** Default production composition, real video/text rendering and actual Android
 * TTS IPC. The separate fixture service synthesizes deterministic silence; these
 * assertions prove request preservation and configuration, never audible quality. */
@UnstableApi
@RunWith(AndroidJUnit4::class)
class AudioCommandsAndroidTest {
    private val instrument get() = InstrumentationRegistry.getInstrumentation()

    @Before fun resetPreferences() {
        instrument.targetContext.getSharedPreferences("player", Context.MODE_PRIVATE).edit().clear()
            .putBoolean("cache", false).putBoolean("narration", true).putInt("orientation", 0).commit()
        instrument.targetContext.getSharedPreferences("playback-measurements", Context.MODE_PRIVATE).edit().clear().commit()
    }

    private fun waitFor(message: String, timeoutMs: Long = 25_000, condition: () -> Boolean) {
        val deadline = SystemClock.elapsedRealtime() + timeoutMs
        while (SystemClock.elapsedRealtime() < deadline) {
            var ready = false
            instrument.runOnMainSync { ready = condition() }
            if (ready) return
            Thread.sleep(40)
        }
        fail(message)
    }

    private fun fixture(name: String): File = File(instrument.targetContext.cacheDir, "audio-command-$name").also { file ->
        instrument.context.assets.open("ssa_nonloss/$name").use { input ->
            file.outputStream().use { output -> input.copyTo(output) }
        }
    }

    private fun accepted(session: PlaybackSession, command: AudioCommand) {
        val result = session.audioCommands.submit(AudioCommandRequest(session.audioCommands.snapshot().context.generation, command))
        assertTrue("Expected acceptance, got $result", result is AudioCommandDecision.Accepted)
    }

    @Test fun commandsDuringActualSpeechPreserveEverySelectedAssOccurrenceAndBothRealRepeats() {
        // Expectations are independently taken from the versioned ASS fixture,
        // never generated by the parser or deduplicated after observation.
        val source = listOf("Non-perte — panneau externe ; accès réservé.",
            "Non-perte — dialogue externe un ; Alice arrive.",
            "Non-perte — dialogue externe deux ; Bob répond.",
            "Non-perte — dialogue externe trois ; Alice repart.",
            "Non-perte — reprise externe ; encore une fois.",
            "Non-perte — reprise externe ; encore une fois.")
        val requests = Collections.synchronizedList(mutableListOf<String>())
        val completed = Collections.synchronizedList(mutableListOf<String>())
        val observedIds = Collections.synchronizedList(mutableListOf<String>())
        fun observed() = synchronized(requests) { requests.toList() }
        val errors = Collections.synchronizedList(mutableListOf<String>())
        val activity = AtomicReference<MainActivity>()
        val receiverFailure = AtomicReference<Throwable>()
        var edited = 0
        val context = instrument.targetContext
        val receiver = object : BroadcastReceiver() {
            override fun onReceive(context: Context?, intent: Intent?) {
                val text = intent?.getStringExtra("text") ?: return
                if (intent.action == FixtureSpeechService.ALL_REQUESTS_ACTION) { requests += text; return }
                if (intent.action != FixtureSpeechService.OBSERVATION_ACTION) return
                when (intent.getStringExtra("event")) {
                    "completed" -> completed += text
                    "injected_error" -> errors += "Unexpected fixture synthesis failure"
                    "received" -> try {
                        val session = requireNotNull(activity.get()).session
                        val before = session.machine.snapshot()
                        val id = requireNotNull(before.speakingId) {
                            "The service's actual request was not associated with an active utterance"
                        }
                        val pending = session.machine.pendingTexts()
                        val plan = session.machine.pendingPlan()
                        val playbackIntent = session.player.playWhenReady
                        val selected = session.player.trackSelectionParameters
                        val media = session.player.currentMediaItem
                        val voicePreferences = listOf(session.prefs.voiceVolume, session.prefs.speechRate,
                            session.prefs.enginePackage, session.prefs.voiceName, session.prefs.mode)
                        val index = edited++
                        val movie = if (index % 2 == 0) .6f else .7f
                        val ratio = if (index % 2 == 0) .25f else .4f
                        accepted(session, AudioCommand.SetLevels(movie, ratio))
                        accepted(session, AudioCommand.SetDuckingTiming(160 + index * 40, 500 + index * 100, 350 + index * 50))
                        accepted(session, AudioCommand.SetSpectralDucking(index % 2 == 0))
                        accepted(session, AudioCommand.SetDsp(speechDsp(index)))
                        assertEquals(speechDsp(index), requireNotNull(session.audioCommands.snapshot().dsp).submittedSettings)
                        assertEquals("The film target is normal volume × retained ratio", movie * ratio,
                            session.player.volume, .00001f)
                        assertEquals(before, session.machine.snapshot())
                        assertEquals(pending, session.machine.pendingTexts())
                        assertEquals(plan, session.machine.pendingPlan())
                        assertEquals(playbackIntent, session.player.playWhenReady)
                        assertEquals(selected, session.player.trackSelectionParameters)
                        assertEquals(media, session.player.currentMediaItem)
                        assertEquals(voicePreferences, listOf(session.prefs.voiceVolume, session.prefs.speechRate,
                            session.prefs.enginePackage, session.prefs.voiceName, session.prefs.mode))
                        assertEquals(id, session.machine.snapshot().speakingId)
                        observedIds += id
                    } catch (failure: Throwable) { receiverFailure.compareAndSet(null, failure) }
                }
            }
        }
        ContextCompat.registerReceiver(context, receiver, IntentFilter().apply {
            addAction(FixtureSpeechService.ALL_REQUESTS_ACTION)
            addAction(FixtureSpeechService.OBSERVATION_ACTION)
        }, ContextCompat.RECEIVER_EXPORTED)
        var video: File? = null
        var subtitles: File? = null
        val preferences = PlayerPreferences(context).apply {
            enginePackage = instrument.context.packageName
            voiceName = "fixture-fr"
            setMode(NarrationMachine.Mode.COMFORT)
        }
        try {
            val actualVideo = fixture("ass_nonloss_video.mkv").also { video = it }
            val actualSubtitles = fixture("ass_nonloss_external.ass").also { subtitles = it }
            ActivityScenario.launch(MainActivity::class.java).use { scenario ->
                scenario.onActivity { current ->
                    activity.set(current)
                    current.session.player.addListener(object : Player.Listener {
                        override fun onPlayerError(error: PlaybackException) { errors += error.errorCodeName }
                    })
                    current.session.open(SavedMedia(Uri.fromFile(actualVideo).toString(), "Synthetic audio-command fixture",
                        subtitlePath = actualSubtitles.path, subtitleMime = MimeTypes.TEXT_SSA))
                }
                waitFor("The real source, ASS track and fixture TTS did not become ready") {
                    val session = activity.get().session
                    session.player.playbackState == Player.STATE_READY && session.speech.isReady &&
                        session.selectedTextId() == "external-subtitle"
                }
                scenario.onActivity { current ->
                    assertTrue("Paused preparation must not synthesize", observed().isEmpty())
                    assertFalse(current.session.prefs.cacheEnabled)
                    current.session.play()
                }
                waitFor("Playback did not finish with all text occurrences drained", 45_000) {
                    receiverFailure.get()?.let { throw AssertionError("An audio command altered active narration", it) }
                    val session = activity.get().session
                    val state = session.machine.snapshot()
                    session.player.playbackState == Player.STATE_ENDED && state.speakingId == null &&
                        state.pendingCount == 0 && !state.wantsPlayback
                }
                waitFor("The service did not finish every source request") { synchronized(completed) { completed.size >= source.size } }
                waitFor("The nonzero final hold/release did not restore the film target") {
                    val session = activity.get().session
                    session.player.volume == session.prefs.movieVolume
                }
                instrument.waitForIdleSync()
                receiverFailure.get()?.let { throw AssertionError("An audio command altered active narration", it) }
                assertEquals("An audio command lost or repeated a real request", source, observed())
                assertEquals(source, synchronized(completed) { completed.toList() })
                assertEquals(6, edited)
                assertEquals("Distinct source occurrences must keep distinct utterance IDs", 6,
                    synchronized(observedIds) { observedIds.toSet().size })
                assertTrue("The real player or voice failed: $errors", errors.isEmpty())
                scenario.onActivity { current ->
                    val session = current.session
                    assertEquals(AudioSettings(.7f, .4f, 360, 1_000, 600, false, speechDsp(5)),
                        session.audioCommands.snapshot().context.requested)
                    assertEquals(.7f, session.player.volume, .00001f)
                    assertFalse(session.player.playWhenReady)
                    assertFalse(session.machine.snapshot().wantsPlayback)
                    assertFalse(session.movieAudio.speaking)
                    assertEquals(0, session.speech.hits)
                    assertEquals(0, session.speech.preparedCount)
                }
            }
        } finally {
            context.unregisterReceiver(receiver)
            preferences.enginePackage = ""
            video?.delete(); subtitles?.delete()
        }
    }

    private fun speechDsp(index: Int) = AudioDspSettings(enabled = true,
        preampDb = -3.0 - index, balance = if (index % 2 == 0) -.25 else .25,
        mono = index % 2 == 0, limiterCeilingDb = -1.0 - index / 2.0,
        limiterReleaseMs = 100 + index * 25,
        band3 = AudioEqBand(true, 750.0 + index * 125, 2.0 + index / 2.0, 1.0 + index / 4.0))

    private fun screenshot(name: String) {
        require(name.matches(Regex("[a-z-]+")))
        for (command in listOf("mkdir -p /sdcard/Download/cinema03-tests",
            "screencap -p /sdcard/Download/cinema03-tests/$name.png")) {
            android.os.ParcelFileDescriptor.AutoCloseInputStream(instrument.uiAutomation.executeShellCommand(command))
                .use { it.readBytes() }
        }
    }

    @Test fun realQuickMixControlsExplainAllSettingsResetThemAndNeverRequestSpeech() {
        val requests = Collections.synchronizedList(mutableListOf<String>())
        fun observed() = synchronized(requests) { requests.toList() }
        val context = instrument.targetContext
        val preferences = PlayerPreferences(context).apply {
            enginePackage = instrument.context.packageName
            voiceName = "fixture-fr"
        }
        val receiver = object : BroadcastReceiver() {
            override fun onReceive(context: Context?, intent: Intent?) {
                if (intent?.action == FixtureSpeechService.ALL_REQUESTS_ACTION)
                    intent.getStringExtra("text")?.let { requests += it }
            }
        }
        ContextCompat.registerReceiver(context, receiver, IntentFilter(FixtureSpeechService.ALL_REQUESTS_ACTION),
            ContextCompat.RECEIVER_EXPORTED)
        try {
            ActivityScenario.launch(MainActivity::class.java).use { scenario ->
                val activity = AtomicReference<MainActivity>()
                scenario.onActivity { current ->
                    activity.set(current)
                    current.session.open(SavedMedia("android.resource://${current.packageName}/${R.raw.demonstration}",
                        "Synthetic audio-controls fixture"))
                    current.setFullscreen(true)
                }
                waitFor("The real paused media and voice did not become ready") {
                    val session = activity.get().session
                    session.player.playbackState == Player.STATE_READY && session.speech.isReady
                }
                var before: NarrationMachine.Snapshot? = null
                scenario.onActivity { current ->
                    before = current.session.machine.snapshot()
                    assertFalse(current.session.player.playWhenReady)
                    assertTrue(observed().isEmpty())
                }
                onView(withText("Volumes rapides")).perform(scrollTo(), click())
                onView(withText("Son du film — réglages et explications")).inRoot(isDialog()).check(matches(isDisplayed()))
                screenshot("expert-audio-parameters")
                fun step(description: String) = onView(withContentDescription(description)).inRoot(isDialog()).perform(scrollTo(), click())
                step("Volume du film : diminuer de cinq points de pourcentage")
                step("Son du film pendant la voix : augmenter de cinq points de pourcentage")
                step("Durée de baisse du film : augmenter de 40 millisecondes")
                step("Durée de remontée du film : augmenter de 100 millisecondes")
                step("Attente avant remontée entre deux répliques : augmenter de 50 millisecondes")
                onView(withId(R.id.audio_spectral_toggle)).inRoot(isDialog()).perform(scrollTo(), click())
                onView(withId(R.id.audio_spectral_toggle)).inRoot(isDialog()).check(matches(isChecked()))
                onView(withId(R.id.audio_settings_refresh)).inRoot(isDialog()).perform(scrollTo(), click())
                onView(withId(R.id.audio_settings_state)).inRoot(isDialog()).perform(scrollTo())
                onView(withId(R.id.audio_settings_state)).inRoot(isDialog()).check(matches(withText(containsString("95 %"))))
                screenshot("expert-audio-observations")
                scenario.onActivity { current ->
                    assertEquals(AudioSettings(.95f, .30f, 200, 600, 400, true), current.session.audioCommands.snapshot().context.requested)
                    assertEquals(.95f, current.session.player.volume, .00001f)
                    assertEquals(before, current.session.machine.snapshot())
                    assertFalse(current.session.player.playWhenReady)
                    assertTrue(observed().isEmpty())
                }

                for (label in listOf("Rétablir le volume du film à 100 %", "Rétablir le son pendant la voix à 25 %",
                    "Rétablir Durée de baisse du film : 160 ms", "Rétablir Durée de remontée du film : 500 ms",
                    "Rétablir Attente avant remontée entre deux répliques : 350 ms",
                    "Rétablir le filtre spectral désactivé par défaut")) {
                    onView(withText(label)).inRoot(isDialog()).perform(scrollTo(), click())
                }
                onView(withId(R.id.audio_spectral_toggle)).inRoot(isDialog()).check(matches(not(isChecked())))
                scenario.onActivity { current ->
                    assertEquals(AudioSettings(), current.session.audioCommands.snapshot().context.requested)
                    assertEquals(before, current.session.machine.snapshot())
                    assertTrue(observed().isEmpty())
                    // Reopen the same media while retaining the old dialog:
                    // persistence and a fresh command generation are separate.
                    current.session.open(requireNotNull(current.session.media))
                }
                waitFor("The replacement source did not become ready") { activity.get().session.player.playbackState == Player.STATE_READY }
                step("Volume du film : diminuer de cinq points de pourcentage")
                onView(withId(R.id.audio_settings_result)).inRoot(isDialog()).perform(scrollTo())
                    .check(matches(withText(containsString("autre ouverture"))))
                screenshot("expert-audio-stale-request")
                scenario.onActivity { current ->
                    assertEquals(AudioSettings(), current.session.audioCommands.snapshot().context.requested)
                    assertFalse(current.session.player.playWhenReady)
                    assertNull(current.session.machine.snapshot().speakingId)
                    assertTrue(observed().isEmpty())
                }
                onView(withText("Fermer")).inRoot(isDialog()).perform(click())
                instrument.waitForIdleSync()
                assertTrue("Consulting or changing film audio made an unexpected actual synthesis request", observed().isEmpty())
            }
        } finally { context.unregisterReceiver(receiver); preferences.enginePackage = "" }
    }
}
